export type MessageResponseProps = ComponentProps<typeof Streamdown>;

const streamdownPlugins = { cjk, code, math, mermaid };

export const MessageResponse = memo(
  ({ className, children, ...props }: MessageResponseProps) => {
    const containerRef = useRef<HTMLDivElement>(null);

    useEffect(() => {
      if (!containerRef.current) return;

      const headers = containerRef.current.querySelectorAll("h2, h3");
      headers.forEach((header) => {
        if (header.querySelector(":scope > .n9n-heading-icon")) {
          return;
        }

        const text = (header.textContent ?? "").trim();
        const matched = Object.entries(HEADER_ICON_MAP).find(([key]) =>
          text.includes(key)
        )?.[1] ?? { name: "sparkles", color: "%2394a3b8" };

        const icon = document.createElement("span");
        icon.className = "n9n-heading-icon";
        icon.setAttribute("aria-hidden", "true");
        icon.style.backgroundImage = `url(https://api.iconify.design/lucide/${matched.name}.svg?color=${matched.color})`;
        header.prepend(icon);
      });
    }, [children]);

    return (
      <>
        <style jsx global>{`
          .message-markdown h2,
          .message-markdown h3 {
            display: flex;
            align-items: center;
            gap: 0.55rem;
          }

          .message-markdown .n9n-heading-icon {
            display: inline-block;
            flex: 0 0 auto;
            width: 1.05rem;
            height: 1.05rem;
            background-repeat: no-repeat;
            background-position: center;
            background-size: contain;
            opacity: 0.9;
          }

          .message-markdown h3 .n9n-heading-icon {
            width: 0.92rem;
            height: 0.92rem;
          }
        `}</style>
        <div ref={containerRef}>
          <Streamdown
            className={cn(
              "message-markdown size-full [&>*:first-child]:mt-0 [&>*:last-child]:mb-0",
              className
            )}
            plugins={streamdownPlugins}
            {...props}
          >
            {children}
          </Streamdown>
        </div>
      </>
    );
  },
  (prevProps, nextProps) => prevProps.children === nextProps.children
);

MessageResponse.displayName = "MessageResponse";

